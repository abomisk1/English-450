def khuluq(lid, title, page, hook, objective, ayah, ayah_ref, hadith, hadith_intro,
           hadith_takhrij, interactions, summary, quiz, extra_cards=None, family=None):
    """قالب موحّد لدرس خُلُق: آية ثم حديث، كما رتّبها الكتاب."""
    cards = []
    if extra_cards:
        cards += extra_cards
    cards.append(card("c1", "quran", ayah, "quran", page=page, ref=ayah_ref,
                      level="brief", title="قَالَ اللهُ تَعَالَى"))
    cards.append(card("c2", "hadith", hadith, "book", page=page, level="brief",
                      title=hadith_intro, note=hadith_takhrij))
    return lesson(lid, title, [page], hook, objective, cards, interactions, summary, quiz,
                  tags=["أخلاق"], family=family)


